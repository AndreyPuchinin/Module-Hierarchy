class RangeMapper:
    """
    АТОМАРНАЯ МЕХАНИКА МАТЕМАТИЧЕСКОГО ПРИВЕДЕНИЯ ЗНАЧЕНИЙ К ПРЕДЕЛАМ ШКАЛЫ (разными методами).
    
    Нижняя точка Ромба МИ. Чистая математика.
    Механика меняется лишь по крайней необходимости.
    
    ПРИНЦИП ДИНАМИЧЕСКОЙ НЕЯВНОЙ СИГНАТУРЫ:
    - Функции Механики (clamp, map) имеют минимальную сигнатуру (только само значение).
    - Все границы и диапазоны передаются ИСКЛЮЧИТЕЛЬНО через сеттеры.
    - Дефолтные значения устанавливаются автоматически.
    """
    
    def __init__(self):
        """
        Инициализация маппера с дефолтными значениями всех параметров (границ).
        """
        # Дефолтные границы для режима "Обрубание хвостов"
        self._clamp_min = 0.0
        self._clamp_max = 1.0
        
        # Дефолтные границы для режима "Пропорциональное приведение"
        self._src_min = 0.0
        self._src_max = 1.0
        self._dst_min = 0.0
        self._dst_max = 1.0
    
    # ==========================================
    # СЕТТЕРЫ (Настройка границ)
    # ==========================================
    
    def set_clamp_bounds(self, min_val, max_val):
        """
        Устанавливает границы для режима "Обрубание хвостов".
        
        СИГНАТУРА:
        Вход: min_val (float), max_val (float)
        Выход: None
        """
        self._clamp_min = float(min_val)
        self._clamp_max = float(max_val)
    
    def set_map_bounds(self, src_min, src_max, dst_min, dst_max):
        """
        Устанавливает границы для режима "Пропорциональное приведение".
        
        СИГНАТУРА:
        Вход: src_min, src_max, dst_min, dst_max (float)
        Выход: None
        """
        self._src_min = float(src_min)
        self._src_max = float(src_max)
        self._dst_min = float(dst_min)
        self._dst_max = float(dst_max)
    
    # ==========================================
    # ФУНКЦИИ МЕХАНИКИ (Запуск) Число самих методов Механик можно дополнять!
    # ==========================================
    
    def clamp(self, value):
        """
        МЕХАНИКА 1: "Обрубание хвостов".
        Если число за пределами отрезка [min, max], приводится к пределу.
        
        СИГНАТУРА:
        Вход: value (float | int) - исходное значение
        Выход: float - приведенное значение
        """
        return max(self._clamp_min, min(self._clamp_max, float(value)))
    
    def map(self, value):
        """
        МЕХАНИКА 2: Пропорциональное приведение.
        Приводит значение из вторичной шкалы к первичной, сохраняя пропорцию.
        
        СИГНАТУРА:
        Вход: value (float | int) - значение во вторичной шкале
        Выход: float - приведенное значение
        """
        if self._src_max == self._src_min:
            return float(self._dst_min) # Защита от деления на ноль
        
        normalized = (float(value) - self._src_min) / (self._src_max - self._src_min)
        return self._dst_min + normalized * (self._dst_max - self._dst_min)
